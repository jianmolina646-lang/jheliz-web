import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID,createHmac} from 'node:crypto';
import Fastify from 'fastify';
import {db} from '../src/db.js';
import {mercadoPagoSchema} from '../src/mercadopago-schema.js';
import {applyMercadoPago,selectMercadoPago,registerMercadoPago} from '../src/mercadopago.js';
import {approveOrder} from '../src/commerce.js';
import {selectPayment} from '../src/payment-choice.js';
test('MP isolated PostgreSQL: concurrency, no stock, renewals, mismatches and provider locking',{skip:process.env.RUN_MP_TEST!=='1'},async()=>{
 assert.equal(new URL(process.env.DATABASE_URL).pathname,'/marketing_mp_test');
 try{
  await db.query(mercadoPagoSchema);
  await db.query('TRUNCATE mp_checkouts,mp_payments,mp_webhook_queue,orders,stock,products,instances CASCADE');
  const app=Fastify();const secret='synthetic';registerMercadoPago(app,()=>({secret}));
  const body={type:'payment',data:{id:'987654321'}};
  assert.equal((await app.inject({method:'POST',url:'/webhooks/mercadopago/?data.id=987654321',payload:body})).statusCode,401);
  const ts=String(Date.now()),rid='synthetic-request';
  const sig=createHmac('sha256',secret).update(`id:987654321;request-id:${rid};ts:${ts};`).digest('hex');
  const opts={method:'POST',url:'/webhooks/mercadopago/?data.id=987654321',payload:body,headers:{'x-request-id':rid,'x-signature':`ts=${ts},v1=${sig}`}};
  assert.equal((await app.inject(opts)).statusCode,200);assert.equal((await app.inject(opts)).statusCode,200);
  assert.equal((await app.inject({...opts,payload:{...body,data:{id:'987654322'}}})).statusCode,400);
  assert.equal((await db.query("SELECT version::int FROM mp_webhook_queue WHERE payment_id='987654321'")).rows[0].version,2);
  await app.close();
  const [i]=(await db.query("INSERT INTO instances(name) VALUES('MP sales test') RETURNING id")).rows;
  const [product]=(await db.query("INSERT INTO products(code,name,price_cents,days) VALUES('mp-test','Test',1000,30) RETURNING id")).rows;
  const config={collector:'123',token:'synthetic',webhook:'https://example.invalid'};
  let n=1000;
  async function order(){return (await db.query("INSERT INTO orders(instance_id,jid,customer,product_id,product_name,price_cents,days) VALUES($1,$2,'Test',$3,'Test',1000,30) RETURNING *",[i.id,randomUUID()+'@s.whatsapp.net',product.id])).rows[0];}
  const state=async o=>(await db.query('SELECT * FROM orders WHERE id=$1',[o.id])).rows[0];
  const stock=()=>db.query('INSERT INTO stock(product_id,secret,fingerprint) VALUES($1,$2,$3)',[product.id,'synthetic',randomUUID()]);
  const pay=o=>({id:++n,collector_id:123,external_reference:'wa:'+o.id,live_mode:true,currency_id:'PEN',transaction_amount:10,status:'approved',date_approved:new Date().toISOString()});
  let creates=0;
  const fake=async()=>({id:'pref-'+(++creates),collector_id:123,init_point:'https://www.mercadopago.com.pe/checkout?pref='+creates});
  const choose=o=>selectMercadoPago(i.id,o.jid,fake,config);
  const a=await order();await stock();
  const links=await Promise.all([choose(a),choose(a)]);assert.equal(creates,1);assert.equal(links[0].url,links[1].url);
  assert.match((await selectPayment(i.id,a.jid,'BINANCE')).error,/Mercado Pago/);
  await assert.rejects(approveOrder(a.id,'manual-reference',null));
  const p=pay(a);
  const applied=await Promise.all([applyMercadoPago(p,config),applyMercadoPago(p,config)]);
  assert.equal(applied.filter(x=>x==='APPLIED').length,1);assert.equal((await state(a)).status,'APPROVED');
  assert.equal(await applyMercadoPago(pay(a),config),'ORDER_REVIEW');
  const b=await order();await choose(b);
  assert.equal(await applyMercadoPago(pay(b),config),'NO_STOCK');assert.equal((await state(b)).status,'PENDING');
  assert.match((await choose(b)).error,/no vuelvas a pagar/);
  const held=(await db.query('SELECT payment_id FROM mp_payments WHERE order_id=$1',[b.id])).rows[0];await stock();
  assert.equal(await applyMercadoPago({...pay(b),id:held.payment_id},config),'APPLIED');
  const c=await order();await choose(c);await stock();
  assert.equal(await applyMercadoPago({...pay(c),transaction_amount:9},config),'UNVERIFIED');assert.equal((await state(c)).status,'PENDING');
  assert.equal(await applyMercadoPago({...p,external_reference:'wa:'+c.id},config),'IGNORED');
  await db.query("UPDATE orders SET status='REJECTED' WHERE id=$1",[c.id]);assert.equal(await applyMercadoPago(pay(c),config),'ORDER_REVIEW');
  const d=await order();await db.query("UPDATE orders SET lemon_check='QR_SELECTED' WHERE id=$1",[d.id]);assert.ok((await choose(d)).error);
  const e=await order();await choose(e);
  await db.query("UPDATE orders SET status='DELIVERED',expires_at=now()+interval '10 days' WHERE id=$1",[a.id]);
  await db.query('UPDATE orders SET renewal_of=$1 WHERE id=$2',[a.id,e.id]);
  const old=(await state(a)).expires_at;
  const renewal=pay(e);assert.equal(await applyMercadoPago(renewal,config),'APPLIED');
  const end=(await state(a)).expires_at;assert.ok(end>old);await applyMercadoPago(renewal,config);assert.deepEqual((await state(a)).expires_at,end);
  await applyMercadoPago({...renewal,status:'refunded',transaction_amount_refunded:10},config);assert.equal((await state(e)).status,'REVIEW');
 }finally{await db.end();}
});
